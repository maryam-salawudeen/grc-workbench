type Treatment = 'mitigate' | 'accept' | 'transfer' | 'avoid';

export interface ModelRisk {
  key: string;
  title: string;
  category: string;
  /** Asset name as it appears in `assets`. */
  asset: string;
  /** Phrases (lowercase) that identify a learner's risk as this one. */
  keywords: string[];
  likelihood: number;
  impact: number;
  residual_likelihood: number;
  residual_impact: number;
  treatment: Treatment;
  /** Other treatments that also earn full marks. */
  alsoAccept?: Treatment[];
  controls: string[];
  quant?: { asset_value: number; exposure_factor: number; aro: number };
  why: { scoring: string; treatment: string; controls: string };
}

export interface Scenario {
  id: string;
  org: string;
  sector: string;
  difficulty: 1 | 2 | 3 | 4 | 5;
  minutes: number;
  summary: string;
  focus: string[];
  brief: { heading: string; body: string[] }[];
  tasks: string[];
  people: [name: string, title: string, department: string][];
  /** name, type, classification, criticality 1-5, value (CAD), owner index into people, description */
  assets: [string, string, string, number, number, number, string][];
  /** name, service, owner index, data access, criticality, system access, certifications, last assessed (days ago or null), status */
  vendors: [string, string, number, string, string, boolean, string, number | null, string][];
  /** Control library status at the start; anything not listed is not implemented. */
  controls: Partial<Record<string, ControlStatus>>;
  risks: ModelRisk[];
}

